-- =====================================================================
-- Миграция 0007: расчётная стоимость за единицу.
--
-- Стоимость единицы = себестоимость(CNY) × курс юаня к рублю ×
--                      (1 + пошлина% / 100) + трансфер прайс(₽).
--
-- parts получает курс и пошлину (себестоимость CNY и трансфер прайс уже
-- были) — это "текущие" (последнего поступления) значения, показываемые
-- в карточке детали. receipts получает трансфер прайс за единицу для
-- конкретной партии (себестоимость CNY, курс и пошлина у партии уже были).
-- Оба безопасно повторно выполнимы (IF NOT EXISTS).
-- =====================================================================

ALTER TABLE parts ADD COLUMN IF NOT EXISTS exchange_rate NUMERIC;
ALTER TABLE parts ADD COLUMN IF NOT EXISTS customs_duty_percent NUMERIC;

ALTER TABLE receipts ADD COLUMN IF NOT EXISTS transfer_price_rub NUMERIC;
