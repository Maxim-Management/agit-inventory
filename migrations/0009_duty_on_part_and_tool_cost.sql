-- Миграция 0009: таможенная пошлина — атрибут позиции, а не партии;
-- себестоимость инструмента для расчёта амортизации.
--
-- 1. Таможенная пошлина (customs_duty_percent) раньше указывалась на
--    каждой партии поступления (receipts) отдельно — теперь она относится
--    к самой позиции (parts.customs_duty_percent, это поле уже
--    существовало) и одна и та же для всех партий этой детали. Колонка
--    receipts.customs_duty_percent удаляется — расчёт стоимости за единицу
--    (app/costing.py, app/stock.py) теперь везде берёт пошлину из карточки
--    детали, а не из партии.
-- 2. У инструмента (tools) появляется поле себестоимости (cost_rub, ₽) —
--    база для расчёта начисленной амортизации: 1/18 стоимости за каждый
--    полный месяц с даты ввода в эксплуатацию (commissioned_date), см.
--    app/tools.py: tool_depreciation(). Рентабельность инструмента теперь
--    учитывает амортизацию: Выручка − (амортизация + стоимость ремонтов).
-- =====================================================================

ALTER TABLE receipts DROP COLUMN IF EXISTS customs_duty_percent;

ALTER TABLE tools ADD COLUMN IF NOT EXISTS cost_rub NUMERIC;
